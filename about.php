    <div class="about-card">
        <h2>Our Mission</h2>
        <p>Our mission is to modernize beer tasting events by empowering hosts and attendees with event coordination, real time reviews, and crowdsourced taste analytics.</p>
    </div>

    <div class="about-card">
        <h2>The Problem & Our Value</h2>
        <p><strong>The Challenge:</strong> Craft beer tastings, festival bottle shares, and home tasting parties often rely on paper scoreboards and mental notes. Attendees quickly lose track of what they sampled, while hosts have no easy way to tally scores or understand which beers were the true crowd favorites.</p>
        <div class="value-block">
            <p><strong>The Value We Deliver:</strong> Taster replaces manual guesswork with a live digital platform:</p>
            <ul>
                <li><strong>For Attendees:</strong> Log ratings and reviews, compare with friends, and save favorites to a personal profile.</li>
                <li><strong>For Hosts:</strong> Event creation, track attendee participation live, and instantly view aggregated analytics on the crowd's favorite drinks.</li>
            </ul>
        </div>
    </div>

    <div class="about-card">
        <h2>Future Evolution & Startup Potential</h2>
        <p>While Taster began as an academic project, its strongest commercial potential lies in partnering directly with craft breweries and taprooms. Taster captures live consumer sentiment, preferences, and ratings. As a commercial product, Taster could monetize this data by selling analytics and consumer insight reports back to breweries. This gives brewmasters and marketing teams valuable insights, allowing them to validate pilot batches, refine recipes, track flavor trends, and forecast demand before investing in full scale brewing and distribution.</p>
    </div>

